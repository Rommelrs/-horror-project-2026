using System.Collections.Generic;
using System.Text;
using UnityEngine;
using UnityEngine.AI;
using UnityEngine.InputSystem;
#if UNITY_EDITOR
using UnityEditor;
#endif

/// <summary>
/// Gym-only test bench for enemy AI (page 1 = QuestionerEnemy, page 2 = BagBearerEnemy; Numpad 0 switches page). Press a key (see the on-screen panel) and the player is teleported into
/// a prepared scenario room while fresh Questioner(s) are spawned. Also has debug tools: stability +/-, give gun + ammo,
/// infinite ammo, invincible mode, slow-mo, per-enemy AI toggles (sidestep / advanced pathfinding / dynamic speed / freeze).
/// The rooms and scenarios are generated by Tools > Questioner Test Bench > Rebuild Bench In Open Scene.
/// Nothing happens until you press a scenario key, so the Gym behaves as before until then.
/// </summary>
public class QuestionerTestBench : MonoBehaviour
{
    /// <summary>Which enemy a scenario page is about. Numpad 0 flips between the pages.</summary>
    public enum EnemyKind { Questioner, BagBearer }

    [System.Serializable]
    public class EnemySpawn
    {
        public Transform point;
        [Tooltip("Tick to spawn a different enemy than the scenario's page (e.g. a Questioner inside a BagBearer scenario).")]
        public bool overrideKind;
        public EnemyKind kind;
        [Tooltip("Tick to force a different EnemyType than the prefab's (Aggressive). Wandering = patrols its waypoints / stands still until it sees or hears you.")]
        public bool overrideType;
        public EnemyType type = EnemyType.Wandering;
        public Transform[] waypoints;
    }

    [System.Serializable]
    public class Scenario
    {
        public string name;
        [Tooltip("Page this scenario belongs to (also the default enemy it spawns).")]
        public EnemyKind kind;
        [TextArea(2, 6)] public string watchFor;
        public Transform playerSpawn;
        public EnemySpawn[] enemies;
        [Range(0, 100)] public int startStability = 100;
        [Tooltip("Gives the pistol + a full magazine + reserve ammo when the scenario starts.")]
        public bool giveGun;
        [Tooltip("Where the shootable pass/fail button floats, in the player spawn's local space (x = right, y = up, z = forward).")]
        public Vector3 buttonOffset = new Vector3(1.8f, 1.3f, 0f);
    }

    public enum Result { None, Pass, Fail }

    [Header("Prefabs / items")]
    public GameObject questionerPrefab;
    public GameObject questionerNoRunningPrefab;
    public GameObject bagBearerPrefab;
    public Item pistolItem;
    public Item ammoItem;
    public int reserveAmmoToGive = 30;

    [Header("Scenarios")]
    public List<Scenario> scenarios = new List<Scenario>();

    [Header("Defaults")]
    public bool godMode = true;
    public bool isolateOtherEnemies = true;

    class Live
    {
        public Enemy enemy;
        public Stats stats;
        public int sideChance;
        public bool advanced;
        public bool dynamicSpeed;
        public float stuckTime;
        public float maxStuckTime;
        public string maxStuckInfo = "";
        public float queuedTime;
        public EnemyKind kind;
        public int throws;                 // BagBearer: bags thrown (loaded bag count dropped)
        public int lastLoaded = -1;
        public float firstThrowTime = -1f;
        public float lastThrowTime = -1f;
        public int attacks;
        public float firstAttackTime = -1f;
        public float firstChaseTime = -1f;
        public float firstMoveTime = -1f;
        public Vector3 lastPos;
    }

    readonly List<Live> live = new List<Live>();
    readonly List<GameObject> hiddenOthers = new List<GameObject>();
    Transform spawnedParent;

    int current = -1;                       // index into 'scenarios' (global, across both pages)
    EnemyKind page = EnemyKind.Questioner;  // which page the number keys / PgUp / PgDn / panel list work on
    int playerDamageTaken, playerHitsTaken;
    bool damageHooked;
    float scenarioStartTime;
    bool showPanel = true;
    bool infiniteAmmo;
    bool useNoRunningVariant;
    bool noSidestep, noAdvancedPath, noDynamicSpeed, aiFrozen;
    int timeScaleIndex;
    static readonly float[] TimeScales = { 1f, 0.5f, 0.25f };
    bool addedPistol;
    int addedAmmo;
    string toast = "";
    float toastUntil;

    // Shootable result button (created at runtime, shot with the gun: none -> PASS (green) -> FAIL (red) -> none)
    GameObject buttonGo;
    Renderer buttonRenderer;
    Health buttonHealth;
    int lastButtonShotFrame = -1;
    readonly Dictionary<int, Result> results = new Dictionary<int, Result>();

    GUIStyle boxStyle, labelStyle, headerStyle, tagStyle;

    void Awake()
    {
        var go = new GameObject("SpawnedEnemies");
        go.transform.SetParent(transform, false);
        spawnedParent = go.transform;
        CreateResultButton();
    }

    void CreateResultButton()
    {
        buttonGo = GameObject.CreatePrimitive(PrimitiveType.Cube);
        buttonGo.name = "ScenarioResultButton";
        buttonGo.transform.SetParent(transform, false);
        buttonGo.transform.localScale = new Vector3(0.7f, 0.7f, 0.12f);
        buttonRenderer = buttonGo.GetComponent<Renderer>();
        buttonRenderer.material.color = ResultColor(Result.None);
        buttonHealth = buttonGo.AddComponent<Health>();
        buttonHealth.OnDamageTaken += OnButtonShot;
        if (buttonHealth.OnDeath == null) buttonHealth.OnDeath = new UnityEngine.Events.UnityEvent();
        buttonHealth.OnDeath.AddListener(OnButtonKilled);
        buttonGo.SetActive(false);
    }

    void OnButtonShot(int damage) { CycleResult(); }
    void OnButtonKilled() { CycleResult(); }

    void CycleResult()
    {
        // Health fires either OnDeath or OnDamageTaken for one bullet; the frame guard makes sure we only count a bullet once.
        if (lastButtonShotFrame == Time.frameCount) return;
        lastButtonShotFrame = Time.frameCount;
        if (buttonHealth != null) buttonHealth.ResetHealth();
        if (current < 0) return;

        Result next = (Result)(((int)GetResult(current) + 1) % 3);
        results[current] = next;
        RefreshButton();
        Toast(scenarios[current].kind + " " + LocalNumber(current) + ": " + (next == Result.Pass ? "PASSED" : next == Result.Fail ? "FAILED" : "result cleared"));
    }

    Result GetResult(int index)
    {
        return results.TryGetValue(index, out var r) ? r : Result.None;
    }

    static Color ResultColor(Result r)
    {
        switch (r)
        {
            case Result.Pass: return new Color(0.15f, 0.85f, 0.25f);
            case Result.Fail: return new Color(0.9f, 0.15f, 0.15f);
            default: return new Color(0.95f, 0.7f, 0.15f);
        }
    }

    void RefreshButton()
    {
        if (buttonRenderer != null && current >= 0) buttonRenderer.material.color = ResultColor(GetResult(current));
    }

    void PlaceButton(Scenario sc)
    {
        if (buttonGo == null || sc.playerSpawn == null) return;
        Vector3 pos = sc.playerSpawn.TransformPoint(sc.buttonOffset);
        Vector3 toPlayer = sc.playerSpawn.position - pos; toPlayer.y = 0f;
        buttonGo.transform.SetPositionAndRotation(pos, toPlayer.sqrMagnitude > 0.01f ? Quaternion.LookRotation(toPlayer) : sc.playerSpawn.rotation);
        buttonGo.SetActive(true);
        if (buttonHealth != null) buttonHealth.ResetHealth();
        RefreshButton();
    }

    void OnDestroy()
    {
        Time.timeScale = 1f;

        if (damageHooked && Player.instance != null && Player.instance.health != null)
            Player.instance.health.OnDamageTaken -= OnPlayerDamaged;

        var p = Player.instance;
        if (p != null && p.inventory != null)
        {
            if (addedAmmo > 0 && ammoItem != null) p.inventory.RemoveItem(ammoItem, addedAmmo);
            if (addedPistol && pistolItem != null) p.inventory.RemoveItem(pistolItem, 1);
        }
        if (p != null)
        {
            if (p.health != null) p.health.Invincible = false;
            if (p.playerWeaponSystem != null) p.playerWeaponSystem.infiniteAmmo = false;
        }
    }

    // ----------------------------------------------------------------- input

    void Update()
    {
        var p = Player.instance;
        if (p != null)
        {
            if (p.health != null) p.health.Invincible = godMode;
            if (p.playerWeaponSystem != null && infiniteAmmo) p.playerWeaponSystem.infiniteAmmo = true;
        }

        TrackEnemies();
        TrackProjectiles();

        var kb = Keyboard.current;
        if (kb == null || p == null) return;

        // Page switch (Questioner <-> BagBearer scenario lists)
        if (kb.numpad0Key.wasPressedThisFrame)
        {
            page = page == EnemyKind.Questioner ? EnemyKind.BagBearer : EnemyKind.Questioner;
            Toast("Page: " + page + " (" + PageIndices(page).Count + " scenarios) - press Numpad 1-9 / PgDn");
        }

        // Scenario selection (numbers are relative to the current page)
        Key[] numpad = { Key.None, Key.Numpad1, Key.Numpad2, Key.Numpad3, Key.Numpad4, Key.Numpad5, Key.Numpad6, Key.Numpad7, Key.Numpad8, Key.Numpad9 };
        var pageList = PageIndices(page);
        for (int i = 1; i <= 9; i++)
            if (kb[numpad[i]].wasPressedThisFrame && i - 1 < pageList.Count) LoadScenario(pageList[i - 1]);
        if (pageList.Count > 0)
        {
            int pos = pageList.IndexOf(current);
            if (kb.pageDownKey.wasPressedThisFrame) LoadScenario(pageList[pos < 0 ? 0 : (pos + 1) % pageList.Count]);
            if (kb.pageUpKey.wasPressedThisFrame) LoadScenario(pageList[pos <= 0 ? pageList.Count - 1 : pos - 1]);
        }
        if (kb.f5Key.wasPressedThisFrame && current >= 0) LoadScenario(current);
        if (kb.f11Key.wasPressedThisFrame) { ClearEnemies(); Toast("Enemies cleared"); }
        if (kb.deleteKey.wasPressedThisFrame) { results.Clear(); RefreshButton(); Toast("All scenario results cleared"); }

        // Player tools
        bool shift = kb.leftShiftKey.isPressed || kb.rightShiftKey.isPressed;
        if (kb.f6Key.wasPressedThisFrame) AddStability(shift ? -50 : -10);
        if (kb.f7Key.wasPressedThisFrame) AddStability(shift ? 50 : 10);
        if (kb.f8Key.wasPressedThisFrame) { GiveGun(); Toast("Gun + full mag + " + reserveAmmoToGive + " reserve"); }
        if (kb.f9Key.wasPressedThisFrame)
        {
            infiniteAmmo = !infiniteAmmo;
            if (!infiniteAmmo && p.playerWeaponSystem != null) p.playerWeaponSystem.infiniteAmmo = false;
            Toast("Infinite ammo " + (infiniteAmmo ? "ON" : "OFF"));
        }
        if (kb.f10Key.wasPressedThisFrame) { godMode = !godMode; Toast("Invincible mode " + (godMode ? "ON" : "OFF")); }

        // Enemy toggles (apply live to the spawned enemies and to the next spawns)
        if (kb.numpadDivideKey.wasPressedThisFrame) { noSidestep = !noSidestep; ApplyToggles(); Toast("Sidestep " + (noSidestep ? "DISABLED" : "enabled")); }
        if (kb.numpadMultiplyKey.wasPressedThisFrame) { noAdvancedPath = !noAdvancedPath; ApplyToggles(); Toast("Advanced pathfinding (offset around player) " + (noAdvancedPath ? "DISABLED" : "enabled")); }
        if (kb.numpadMinusKey.wasPressedThisFrame) { noDynamicSpeed = !noDynamicSpeed; ApplyToggles(); Toast("Dynamic chase speed " + (noDynamicSpeed ? "DISABLED" : "enabled")); }
        if (kb.numpadPeriodKey.wasPressedThisFrame) { aiFrozen = !aiFrozen; ApplyToggles(); Toast("Enemy AI " + (aiFrozen ? "FROZEN" : "running")); }

        // Misc
        if (kb.f1Key.wasPressedThisFrame) showPanel = !showPanel;
        if (kb.f2Key.wasPressedThisFrame)
        {
            isolateOtherEnemies = !isolateOtherEnemies;
            if (isolateOtherEnemies) HideOtherEnemies(); else RestoreOtherEnemies();
            Toast("Other gym enemies " + (isolateOtherEnemies ? "HIDDEN" : "active"));
        }
        if (kb.f3Key.wasPressedThisFrame)
        {
            useNoRunningVariant = !useNoRunningVariant;
            Toast("Variant: " + (useNoRunningVariant ? "QuestionerEnemyNoRunning" : "QuestionerEnemy") + " (applies on next spawn / F5)");
        }
        if (kb.f4Key.wasPressedThisFrame)
        {
            timeScaleIndex = (timeScaleIndex + 1) % TimeScales.Length;
            Time.timeScale = TimeScales[timeScaleIndex];
            Toast("Time scale " + Time.timeScale);
        }
    }

    // ------------------------------------------------------------- scenarios

    /// <summary>One line per spawned enemy with the same timers the panel shows (for automated checks).</summary>
    public string DebugTimers()
    {
        var sb = new System.Text.StringBuilder();
        foreach (var l in live)
            sb.Append((l.kind == EnemyKind.BagBearer ? "[bag throws " + l.throws + " 1stThrow@" + Fmt(l.firstThrowTime) + " lastThrow@" + Fmt(l.lastThrowTime) + " landed " + bagsLanded + " near " + bagsNear + "] " : "")
                + "chase@" + Fmt(l.firstChaseTime) + " moved@" + Fmt(l.firstMoveTime) + " 1stAttack@" + Fmt(l.firstAttackTime) + " attacks " + l.attacks
                + " maxStuck " + l.maxStuckTime.ToString("0.0") + "s" + (l.maxStuckTime > 0f ? " (" + l.maxStuckInfo + ")" : "") + " queued " + l.queuedTime.ToString("0.0") + "s; ");
        return sb.ToString();
    }

    /// <summary>Global scenario indexes belonging to a page, in order.</summary>
    List<int> PageIndices(EnemyKind kind)
    {
        var list = new List<int>();
        for (int i = 0; i < scenarios.Count; i++)
            if (scenarios[i].kind == kind) list.Add(i);
        return list;
    }

    /// <summary>Number shown to the user: position within the scenario's own page, starting at 1.</summary>
    int LocalNumber(int globalIndex)
    {
        if (globalIndex < 0 || globalIndex >= scenarios.Count) return globalIndex + 1;
        return PageIndices(scenarios[globalIndex].kind).IndexOf(globalIndex) + 1;
    }

    GameObject PrefabFor(EnemyKind kind)
    {
        if (kind == EnemyKind.BagBearer) return bagBearerPrefab;
        return useNoRunningVariant && questionerNoRunningPrefab != null ? questionerNoRunningPrefab : questionerPrefab;
    }

    void OnPlayerDamaged(int dmg)
    {
        playerDamageTaken += dmg;
        playerHitsTaken++;
    }

    public void LoadScenario(int index)
    {
        if (index < 0 || index >= scenarios.Count) { Toast("No scenario " + (index + 1)); return; }
        var p = Player.instance;
        if (p == null) return;

        var sc = scenarios[index];
        current = index;
        page = sc.kind;
        scenarioStartTime = Time.time;
        playerDamageTaken = 0;
        playerHitsTaken = 0;
        bagsLanded = 0;
        bagsNear = 0;
        lastBagLandDistance = -1f;
        flyingBags.Clear();
        if (!damageHooked && p.health != null)
        {
            p.health.OnDamageTaken += OnPlayerDamaged;
            damageHooked = true;
        }

        if (isolateOtherEnemies) HideOtherEnemies();
        ClearEnemies();

        // Player
        p.ResetPlayer(); // full health, clears a death pose from a previous scenario
        if (sc.playerSpawn != null) TeleportPlayer(p, sc.playerSpawn);
        if (p.playerStability != null) p.playerStability.stability = Mathf.Clamp(sc.startStability, 0, p.playerStability.maxStability);
        if (sc.giveGun) GiveGun();
        PlaceButton(sc);

        // Enemies
        int offMesh = 0;
        if (sc.enemies != null)
        {
            foreach (var es in sc.enemies)
            {
                if (es == null || es.point == null) continue;
                EnemyKind kind = es.overrideKind ? es.kind : sc.kind;
                var prefab = PrefabFor(kind);
                if (prefab == null) { Toast("No " + kind + " prefab assigned"); continue; }
                Vector3 pos = es.point.position;
                if (NavMesh.SamplePosition(pos, out var hit, 3f, NavMesh.AllAreas)) pos = hit.position;
                else offMesh++;

                var go = Instantiate(prefab, pos, es.point.rotation, spawnedParent);
                go.name = prefab.name + " [bench]";
                var enemy = go.GetComponent<Enemy>();
                if (enemy == null) continue;

                if (es.overrideType) enemy.stats.enemyType = es.type;
                if (es.waypoints != null && es.waypoints.Length > 0) enemy.stats.waypoints = es.waypoints;

                var l = new Live
                {
                    kind = kind,
                    enemy = enemy,
                    stats = enemy.stats,
                    sideChance = enemy.stats.sideStepChance,
                    advanced = enemy.stats.useAdvancedPathfinding,
                    dynamicSpeed = enemy.stats.useDynamicChaseSpeed,
                    lastPos = pos,
                };
                var captured = l;
                enemy.OnAttackStarted.AddListener(() =>
                {
                    captured.attacks++;
                    if (captured.firstAttackTime < 0f) captured.firstAttackTime = Time.time - scenarioStartTime;
                });
                enemy.OnChaseStarted.AddListener(() =>
                {
                    if (captured.firstChaseTime < 0f) captured.firstChaseTime = Time.time - scenarioStartTime;
                });
                live.Add(l);
            }
        }
        ApplyToggles();
        Toast(sc.kind + " " + LocalNumber(index) + ": " + sc.name + (offMesh > 0 ? "   (!) " + offMesh + " enemy spawn(s) not on the NavMesh - rebuild the bench" : ""));
    }

    void TeleportPlayer(Player p, Transform t)
    {
        if (p.controller != null) p.controller.enabled = false;
        p.transform.SetPositionAndRotation(t.position + Vector3.up * 0.1f, t.rotation);
        if (p.controller != null) p.controller.enabled = true;
        p.OnPlayerTelported?.Invoke();
    }

    void ClearEnemies()
    {
        live.Clear();
        for (int i = spawnedParent.childCount - 1; i >= 0; i--)
            Destroy(spawnedParent.GetChild(i).gameObject);
    }

    void HideOtherEnemies()
    {
        foreach (var e in FindObjectsByType<Enemy>(FindObjectsSortMode.None))
        {
            if (e.transform.IsChildOf(spawnedParent)) continue;
            if (!e.gameObject.activeSelf) continue;
            hiddenOthers.Add(e.gameObject);
            e.gameObject.SetActive(false);
        }
    }

    void RestoreOtherEnemies()
    {
        foreach (var g in hiddenOthers) if (g != null) g.SetActive(true);
        hiddenOthers.Clear();
    }

    // --------------------------------------------------------------- tools

    void AddStability(int delta)
    {
        var s = Player.instance != null ? Player.instance.playerStability : null;
        if (s == null) return;
        s.stability = Mathf.Clamp(s.stability + delta, 0, s.maxStability);
        Toast("Stability " + s.stability);
    }

    void GiveGun()
    {
        var p = Player.instance;
        if (p == null) return;
        var inv = p.inventory;
        var w = p.playerWeaponSystem;
        var ammo = ammoItem != null ? ammoItem : (w != null ? w.weaponAmmoItem : null);
        if (inv != null)
        {
            if (pistolItem != null && !inv.HasWeapon() && inv.AddItem(pistolItem, 1)) addedPistol = true;
            if (ammo != null && reserveAmmoToGive > 0)
            {
                inv.HasWeaponAmmo(ammo, out int before);
                inv.AddItem(ammo, reserveAmmoToGive);
                inv.HasWeaponAmmo(ammo, out int after);
                addedAmmo += Mathf.Max(0, after - before);
            }
        }
        if (w != null)
        {
            w.weaponIsEnabled = true;
            w.currentAmmo = w.maxAmmoCapacity;
        }
    }

    void ApplyToggles()
    {
        foreach (var l in live)
        {
            if (l.enemy == null) continue;
            l.stats.sideStepChance = noSidestep ? 0 : l.sideChance;
            l.stats.useAdvancedPathfinding = noAdvancedPath ? false : l.advanced;
            l.stats.useDynamicChaseSpeed = noDynamicSpeed ? false : l.dynamicSpeed;
            l.enemy.PauseEnemyState(aiFrozen);
            // Pausing the state machine alone would leave the agent walking its old path, so stop it too (states un-stop it on resume).
            if (aiFrozen && l.enemy.agent != null && l.enemy.agent.isOnNavMesh) l.enemy.agent.isStopped = true;
        }
    }

    // Thrown bags: remember each flying Projectile's last position; when it vanishes (released to the pool) it has landed.
    readonly Dictionary<Projectile, Vector3> flyingBags = new Dictionary<Projectile, Vector3>();
    readonly List<Projectile> landedScratch = new List<Projectile>();
    int bagsLanded, bagsNear;
    float lastBagLandDistance = -1f;
    const float BagNearDistance = 1.5f;

    void TrackProjectiles()
    {
        var player = Player.instance;
        if (player == null) return;

        foreach (var pr in FindObjectsByType<Projectile>(FindObjectsSortMode.None))
            if (pr != null && pr.gameObject.activeInHierarchy) flyingBags[pr] = pr.transform.position;

        landedScratch.Clear();
        foreach (var kv in flyingBags)
            if (kv.Key == null || !kv.Key.gameObject.activeInHierarchy) landedScratch.Add(kv.Key);

        foreach (var k in landedScratch)
        {
            Vector3 last = flyingBags[k];
            flyingBags.Remove(k);
            Vector3 d = last - player.transform.position; d.y = 0f;
            lastBagLandDistance = d.magnitude;
            bagsLanded++;
            if (lastBagLandDistance <= BagNearDistance) bagsNear++;
        }
    }

    static int LoadedBags(BagBearerEnemy bb)
    {
        int n = 0;
        if (bb.bagBearerReloadGroup != null)
            foreach (var g in bb.bagBearerReloadGroup) if (g.isReloaded) n++;
        return n;
    }

    void TrackEnemies()
    {
        foreach (var l in live)
        {
            if (l.enemy == null) continue;
            var e = l.enemy;
            bool dead = e.health != null && e.health.IsDead;
            Vector3 pos = e.transform.position;
            float moved = (pos - l.lastPos).magnitude / Mathf.Max(Time.deltaTime, 0.0001f);
            l.lastPos = pos;
            if (l.firstMoveTime < 0f && moved > 0.5f) l.firstMoveTime = Time.time - scenarioStartTime;

            bool chasing = e.stateMachine != null && e.stateMachine.CurrentState == e.chaseState;
            float dist = Player.instance != null ? Vector3.Distance(pos, Player.instance.transform.position) : 0f;
            // Waiting in line behind a teammate (Direct Approach queueing) is deliberate, not a stall
            bool queued = chasing && e.chaseState.QueueLeader != null;
            if (queued) l.queuedTime += Time.deltaTime;

            // BagBearer: count thrown bags (loaded-bag count going down)
            if (e is BagBearerEnemy bb)
            {
                int loaded = LoadedBags(bb);
                if (l.lastLoaded >= 0 && loaded < l.lastLoaded)
                {
                    l.throws += l.lastLoaded - loaded;
                    l.lastThrowTime = Time.time - scenarioStartTime;
                    if (l.firstThrowTime < 0f) l.firstThrowTime = l.lastThrowTime;
                }
                l.lastLoaded = loaded;
            }

            bool wantsToMove = chasing && !queued && !dead && !aiFrozen && !e.HoldPositionDuringChase && dist > e.stats.attackRange + 0.5f && Time.time - scenarioStartTime > 4f;
            if (wantsToMove && moved < 0.15f)
            {
                l.stuckTime += Time.deltaTime;
                if (l.stuckTime > l.maxStuckTime) { l.maxStuckTime = l.stuckTime; l.maxStuckInfo = StuckInfo(e); }
            }
            else l.stuckTime = 0f;
        }
    }

    void Toast(string msg)
    {
        toast = msg;
        toastUntil = Time.unscaledTime + 4f;
        Debug.Log("[QuestionerTestBench] " + msg);
    }

    // ------------------------------------------------------------------ GUI

    void BuildStyles()
    {
        float s = Mathf.Max(1f, Screen.height / 1080f);
        int fs = Mathf.RoundToInt(14 * s);
        if (labelStyle != null && labelStyle.fontSize == fs) return;

        var bg = new Texture2D(1, 1);
        bg.SetPixel(0, 0, new Color(0f, 0f, 0f, 0.72f));
        bg.Apply();

        boxStyle = new GUIStyle(GUI.skin.box) { normal = { background = bg } };
        labelStyle = new GUIStyle(GUI.skin.label) { fontSize = fs, richText = true, wordWrap = true, normal = { textColor = Color.white } };
        headerStyle = new GUIStyle(labelStyle) { fontSize = Mathf.RoundToInt(fs * 1.15f), fontStyle = FontStyle.Bold };
        tagStyle = new GUIStyle(labelStyle) { alignment = TextAnchor.MiddleCenter, wordWrap = false };
    }

    void OnGUI()
    {
        BuildStyles();
        float s = Mathf.Max(1f, Screen.height / 1080f);

        if (Time.unscaledTime < toastUntil)
        {
            var r = new Rect(Screen.width * 0.5f - 400 * s, 12 * s, 800 * s, 34 * s);
            GUI.Box(r, GUIContent.none, boxStyle);
            GUI.Label(r, "<b>" + toast + "</b>", tagStyle);
        }

        DrawEnemyTags();
        DrawButtonTag();

        if (!showPanel)
        {
            GUI.Label(new Rect(8 * s, 8 * s, 420 * s, 24 * s), "<color=#9fe>Enemy test bench (" + page + " page) - F1 for help</color>", labelStyle);
            return;
        }

        var sb = new StringBuilder();
        EnemyKind otherPage = page == EnemyKind.Questioner ? EnemyKind.BagBearer : EnemyKind.Questioner;
        sb.AppendLine("<b><color=#9fe>PAGE: " + page.ToString().ToUpper() + "</color></b>   <b>Numpad 0</b> switch to " + otherPage + " page");
