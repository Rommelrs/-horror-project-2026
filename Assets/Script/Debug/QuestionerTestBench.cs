    void DrawEnemyTags()
    {
        var cam = Camera.main;
        if (cam == null) return;
        float s = Mathf.Max(1f, Screen.height / 1080f);

        foreach (var l in live)
        {
            if (l.enemy == null) continue;
            var e = l.enemy;
            Vector3 world = e.transform.position + Vector3.up * 2.4f;
            Vector3 sp = cam.WorldToScreenPoint(world);
            if (sp.z <= 0f) continue;

            float dist = Player.instance != null ? Vector3.Distance(e.transform.position, Player.instance.transform.position) : 0f;
            string state = string.IsNullOrEmpty(e.currentState) ? "?" : e.currentState.Replace("Enemy", "").Replace("State", "");
            float speed = e.agent != null && e.agent.enabled ? e.agent.velocity.magnitude : 0f;
            int hp = e.health != null ? e.health.GetHealthValue() : 0;

            string agentInfo = "";
            if (e.agent != null)
            {
                if (!e.agent.enabled) agentInfo = " agent OFF";
                else if (!e.agent.isOnNavMesh) agentInfo = " <color=#f55>OFF NAVMESH</color>";
                else agentInfo = " path:" + e.agent.pathStatus.ToString().Replace("Path", "");
            }

            string text = "<b>" + state + "</b>  d " + dist.ToString("0.0") + "m  v " + speed.ToString("0.0") + "  hp " + hp + agentInfo;
            if (e is BagBearerEnemy bagE)
                text += "\nbags " + LoadedBags(bagE) + "/" + (bagE.bagBearerReloadGroup != null ? bagE.bagBearerReloadGroup.Length : 0) + "  throws " + l.throws + (e.HoldPositionDuringChase ? "  HOLDING" : "");
            if (l.stuckTime > 1.2f) text += "\n<color=#f55><b>STUCK " + l.stuckTime.ToString("0.0") + "s</b></color> " + StuckInfo(e);
            else if (e.stateMachine != null && e.stateMachine.CurrentState == e.chaseState && e.chaseState.QueueLeader != null)
                text += "\n<color=#6cf><b>QUEUEING</b> behind a teammate (waiting on purpose)</color>";

            int tagLines = text.Split('\n').Length;
            float tagH = (6 + 19 * tagLines) * s;
            var r = new Rect(sp.x - 150 * s, Screen.height - sp.y - 20 * s, 300 * s, tagH);
            GUI.Box(r, GUIContent.none, boxStyle);
            GUI.Label(r, text, tagStyle);
        }
    }

    /// <summary>Why a chasing enemy that wants to move is standing still: agent / path state and what is around him.</summary>
    string StuckInfo(Enemy e)
    {
        var a = e.agent;
        if (a == null) return "no agent";
        if (!a.enabled) return "agent OFF";
        if (!a.isOnNavMesh) return "OFF NAVMESH";

        string info = "path:" + a.pathStatus.ToString().Replace("Path", "")
            + (a.pathPending ? " pending" : "")
            + (a.hasPath ? " rem " + a.remainingDistance.ToString("0.0") : " NO PATH")
            + (a.isStopped ? " STOPPED" : "")
            + " desiredV " + a.desiredVelocity.magnitude.ToString("0.0");

        float nearest = 99f;
        foreach (var o in live)
            if (o.enemy != null && o.enemy != e && !(o.enemy.health != null && o.enemy.health.IsDead))
                nearest = Mathf.Min(nearest, Vector3.Distance(o.enemy.transform.position, e.transform.position));
        if (nearest < 99f) info += " nearestMate " + nearest.ToString("0.0") + "m";
        if (!e.HasLineOfSightToPlayer()) info += " noLOS";
        return info;
    }

